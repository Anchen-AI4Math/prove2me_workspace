def module(name):return 'Theorems.Thm_'+name.replace('.','_')


def literal_public_names(wire,graph):
    stack=[];result={}
    for text in wire.splitlines():
        line=text.strip();match=re.match(r'namespace\s+(\S+)',line)
        if match:stack.append(('namespace',match[1]));continue
        if re.match(r'(?:noncomputable\s+)?section(?:\s|$)',line):stack.append(('section',''));continue
        if re.match(r'end(?:\s|$)',line):
            if stack:stack.pop()
            continue
        match=re.match(r'(?:@\[[^\]]*\]\s*)?(?:noncomputable\s+)?(def|abbrev|theorem|structure|class|inductive)\s+([\w.]+)',line)
        if match:
            name='.'.join([n for k,n in stack if k=='namespace']+[match[2]])
            if name in graph:result[name]=match[1]
    return result


