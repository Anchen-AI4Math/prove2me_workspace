    lean_path = DIRECTORY / f"{stem}.lean"
    request_path = DIRECTORY / f"{stem}.requests.json"
    owner_path = DIRECTORY / f"{stem}.owners.json"
    jsonl_path = DIRECTORY / f"{stem}.jsonl"
    manifest_path = DIRECTORY / f"{stem}.manifest.json"
    request_doc = {
        "schema_version": 2,
        "mode": "structural-kernel-source",
        "certificate_scope": "partial-source-only-two-atomic-structure-families",
        "kernel_metadata_schema": "lean-4.33.1-ConstantInfo-complete-v1",
        "requests": [{key: row[key] for key in REQUEST_FIELDS} for row in basis["records"]],
    }
    owner_doc = {
        "schema_version": 2,
        "mode": "structural-kernel-source",
        "certificate_scope": "partial-source-only-two-atomic-structure-families",
        "lineage": basis["lineage"],
        "full_owner_catalog": base.task_relative(FULL_CATALOG),
        "full_owner_catalog_sha256": basis["full_catalog_sha256"],
        "catalog": base.task_relative(CATALOG),
        "catalog_sha256": base.sha_file(CATALOG),
        "owners": basis["records"],
    }
    base.write_json(request_path, request_doc)
    base.write_json(owner_path, owner_doc)
