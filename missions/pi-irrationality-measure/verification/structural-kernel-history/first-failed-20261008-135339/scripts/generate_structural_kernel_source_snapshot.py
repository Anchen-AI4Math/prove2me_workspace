"""Stage an additive full-kernel source snapshot for two atomic structures.

The output is deliberately separate from the frozen 174-row provider source
cache.  It covers exactly the 25 declarations selected from `Parameters` and
the 49 declarations generated by `AdmissibleParameters`.  The staged Lean
exporter imports the immutable original `OAI...Main` once and uses exact public
Name lookup.  This script never starts Lean or contacts the platform.
"""

