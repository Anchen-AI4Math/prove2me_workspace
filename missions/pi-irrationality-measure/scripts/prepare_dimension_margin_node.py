"""Prepare the frozen Dimension-margin preview for four bounded Lean runs.

Pure Python: no compiler or API call. Existing preview bytes are never changed.
The fourth compiler input extends SnapshotGenerated by an exact proof-reference
collector; all source and generated kernel outputs retain their original paths.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import generate_platform_provider_nodes as nodegen
import preflight_staged_module as runner
import stage_formal_log_base_node as refs_producer

TASK = Path(__file__).resolve().parents[1]
ROOT = TASK.parents[1]
V = TASK / "verification"
STAGE = V / "provider-nodes-preview/OAI_PiExponent_exists_dimension_margin"
KEY = "OAI.NumberTheory.PiExponent.LocalAlgebra.Dimension:5946"
MODULE = "OAI.NumberTheory.PiExponent.LocalAlgebra.Dimension"
PLATFORM = "Definitions.Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension"
CERT = V / "providers-complete-preview/all-shared-safe-leaves/validation/Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension/provider-validation-fast.json"
OLean = V / "staged-build/lib/lean/Definitions/Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension.olean"
PUBLIC = ["OAI.PiExponent.dimensionK", "OAI.PiExponent.dimensionW",
          "OAI.PiExponent.dimensionV", "OAI.PiExponent.dimensionK_le"]
SELF = Path(__file__).resolve()


def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def read(path): return json.loads(path.read_text(encoding="utf-8"))
def rel(path): return path.relative_to(TASK).as_posix()


def require(ok, message):
    if not ok: raise ValueError(message)


def write_new(path, content):
    raw = content if isinstance(content, bytes) else (json.dumps(content, indent=2, ensure_ascii=False) + "\n").encode()
    if path.exists():
        require(path.read_bytes() == raw, "Existing preparation differs; preserve it: " + str(path))
    else:
        path.write_bytes(raw)


def inputs():
    m = read(STAGE / "manifest.json")
    require(m["node"] == KEY and m["theorem_name"] == "OAI.PiExponent.exists_dimension_margin"
            and m["source_graph_name"] == m["theorem_name"]
            and m["source_commit"] == "adc7f1241b42e322a6451854ab7e4b4c146bf78a", "Wrong source node")
    require(m["validated"] is False and m["submission_ready"] is False
            and m["lean_started"] is False and m["api_used"] is False
            and m["full_tree_ready"] is False, "Frozen preview state differs")
    require(m["child_nodes"] == {} and m["node_generated_names"] == []
            and m["restored_local_instances"] == [] and m["definition_certificates"] == []
            and m["source_to_generated_private_kernel_names"] is None,
            "This narrow workflow requires no child/private/local-instance dependency")
    require([x["source_graph_name"] for x in m["public_inline_ci_requests"]] ==
            ["OAI.PiExponent.tendsto_nat_add_one_div_pow",
             "OAI.PiExponent.tendsto_pow_div_nat_add_one",
             "OAI.PiExponent.dimensionK_div_W_le",
             "OAI.PiExponent.dimensionV_geometric_lower",
             "OAI.PiExponent.dimension_error_le",
             "OAI.PiExponent.tendsto_dimension_error_majorant",
             "OAI.PiExponent.tendsto_dimension_collision"], "Unexpected public inline domain")
    require(len(m["definition_dependency_witnesses"]) == 1 and
            m["definition_dependency_witnesses"][0]["source_module"] == MODULE and
            m["definition_dependency_witnesses"][0]["platform_module"] == PLATFORM,
            "Unexpected Definition dependency")
    require(m["whole_import_closure_inventory"]["collisions"] == {}, "Planned public collision")
    for name, expected in m["implementation_sha256"].items():
        require(sha(TASK / "scripts" / name) == expected, "Frozen generator changed: " + name)
    for path, expected in m["input_hashes"].items():
        require(sha(TASK / path) == expected, "Frozen global input changed: " + path)
    for row in m["source_components"]:
        for field in ("source", "facts", "original_source"):
            require(sha(ROOT / row[field]) == row[field + "_sha256"], "Source/AST witness changed")
    require(sha(TASK / m["snapshot_core"]) == m["snapshot_core_sha256"]
            and sha(V / "decl_graph.jsonl") == m["source_graph_sha256"], "Snapshot/Graph changed")
    require(runner.validate_runtime()[1] == m["runtime_sha256"], "Pinned runtime changed")
    require(set(m["outputs_sha256"]) == {Path(m["statement"]).name, Path(m["solution"]).name,
                                          "SnapshotOriginal.lean", "SnapshotGenerated.lean"}, "Wrong four-file domain")
    for name, expected in m["outputs_sha256"].items():
        require(sha(STAGE / name) == expected, "Frozen generated file changed: " + name)
    return m


def dimension_interface(m):
    c = read(CERT)
    require(c.get("validated") is True and c.get("proof_axioms") == "Std3"
            and c.get("source_module") == MODULE and c.get("platform_module") == PLATFORM,
            "Actual Definition certificate identity/validity differs")
    x = c["snapshot_comparison"]
    require(x["compared_names"] == PUBLIC and all(x[y] is True for y in
            ("types_equal", "values_equal", "axioms_equal_and_std3")), "Actual Definition CI comparison incomplete")
    pf = next(row for row in c["preflights"] if row["role"] == "provider-bundle")
    require(pf["output_olean_sha256"] == sha(OLean), "Actual Definition OLean differs from certificate")
    pub = read(V / "providers-complete-preview/all-shared-safe-leaves/validation/Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension/publication.json")
    require(pub["definition_id"] == "8275f04b-be5f-4321-beb8-4670cc14cfc0"
            and pub["last_publish_verdict"]["body"]["status"] == "PUBLISHED", "Published Definition identity differs")
    return {"source_module": MODULE, "platform_module": PLATFORM,
            "certificate": rel(CERT), "certificate_sha256": sha(CERT),
            "publication": rel(V / "providers-complete-preview/all-shared-safe-leaves/validation/Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension/publication.json"),
            "publication_sha256": sha(V / "providers-complete-preview/all-shared-safe-leaves/validation/Def_OAI_NumberTheory_PiExponent_LocalAlgebra_Dimension/publication.json"),
            "definition_id": pub["definition_id"], "output_olean": rel(OLean),
            "output_olean_sha256": sha(OLean), "provided_names": PUBLIC}


def expected():
    m = inputs()
    definition = dimension_interface(m)
    base = STAGE / "SnapshotGenerated.lean"
    out = STAGE / "proof-references.json"
    addon = refs_producer.proof_reference_addon(m["public_inline_ci_requests"], out).encode()
    extended = STAGE / "SnapshotGeneratedWithRefs.lean"
    certified = {"schema_version": 1, "artifact_kind": "dimension-margin-certified-inputs",
                 "node": KEY, "definition": definition, "child_certificates": [],
                 "Lean_started": False, "validated": False, "submission_ready": False}
    pins = {rel(SELF): sha(SELF), rel(Path(refs_producer.__file__)): sha(Path(refs_producer.__file__)),
            rel(STAGE / "manifest.json"): sha(STAGE / "manifest.json"),
            rel(CERT): sha(CERT), definition["publication"]: definition["publication_sha256"],
            rel(OLean): sha(OLean)}
    files = [Path(m["statement"]).name, Path(m["solution"]).name,
             "SnapshotOriginal.lean", extended.name]
    return m, definition, base, addon, extended, out, certified, pins, files


def prepare():
    m, definition, base, addon, extended, out, certified, pins, files = expected()
    write_new(extended, base.read_bytes() + addon)
    ci = STAGE / "certified-inputs.json"
    write_new(ci, certified)
    pins[rel(ci)] = sha(ci)
    manifests = {}
    for i, name in enumerate(files, 1):
        source = STAGE / name
        imports = ["Lean", MODULE] if name == "SnapshotOriginal.lean" else m["imports"]
        doc = {"schema_version": 1, "artifact_kind": "dimension-margin-file-import-certificate",
               "output": source.relative_to(ROOT).as_posix(), "output_sha256": sha(source),
               "imports": imports, "input_hashes": pins, "runtime_sha256": m["runtime_sha256"],
               "node": KEY, "node_validated": False, "timeout_seconds": 300,
               "Lean_started": False, "submission_ready": False}
        mp = STAGE / f"c{i}.json"
        write_new(mp, doc)
        manifests[name] = {"manifest": rel(mp), "manifest_sha256": sha(mp)}
    prep = {"schema_version": 1, "artifact_kind": "dimension-margin-preparation",
            "stage": rel(STAGE), "frozen_manifest_sha256": sha(STAGE / "manifest.json"),
            "frozen_four_files_sha256": m["outputs_sha256"],
            "certified_inputs": rel(ci), "certified_inputs_sha256": sha(ci),
            "base_snapshot": rel(base), "base_snapshot_sha256": sha(base),
            "generated_with_refs": rel(extended), "generated_with_refs_sha256": sha(extended),
            "generated_with_refs_prefix_bytes": base.stat().st_size,
            "reference_addon_sha256": hashlib.sha256(addon).hexdigest(),
            "proof_reference_output": rel(out),
            "proof_reference_requests": ["solution", *[r["generated_name"] for r in m["public_inline_ci_requests"]]],
            "definition": definition, "compile_manifests": manifests,
            "exact_old_snapshot_prefix": True, "Lean_started": False,
            "validated": False, "submission_ready": False}
    write_new(STAGE / "preparation.json", prep)
    return check()


def check():
    m, definition, base, addon, extended, out, certified, pins, files = expected()
    ci = STAGE / "certified-inputs.json"
    require(read(ci) == certified, "Certified actual Definition inputs differ")
    pins[rel(ci)] = sha(ci)
    require(extended.read_bytes() == base.read_bytes() + addon, "Reference companion changed")
    prep = read(STAGE / "preparation.json")
    require(prep["definition"] == definition and prep["frozen_manifest_sha256"] == sha(STAGE / "manifest.json")
            and prep["frozen_four_files_sha256"] == m["outputs_sha256"]
            and prep["generated_with_refs_sha256"] == sha(extended)
            and prep["reference_addon_sha256"] == hashlib.sha256(addon).hexdigest()
            and set(prep["compile_manifests"]) == set(files), "Preparation pins differ")
    for name in files:
        source = STAGE / name
        row = prep["compile_manifests"][name]
        mp = TASK / row["manifest"]
        doc = read(mp)
        require(sha(mp) == row["manifest_sha256"] and doc["output_sha256"] == sha(source)
                and doc["input_hashes"] == pins and doc["timeout_seconds"] == 300,
                "Compiler manifest differs: " + name)
        runner.verify_manifest_inputs(doc)
        runner.verify_source_certificate(source, doc)
        runner.certified_imports(source, doc)
    paths = [STAGE / (name + ".preflight.json") for name in files]
    paths += [ROOT / m[field][side] for field in ("inline_type_json_outputs", "public_inline_type_json_outputs")
              for side in ("original", "generated")]
    paths += [STAGE / "original-type.json", STAGE / "generated-type.json", out]
    require(max(len(str(x.resolve())) for x in paths) < 240, "Compiler artifact exceeds Windows path budget")
    return {"prepared": True, "node": KEY, "stage": rel(STAGE),
            "definition_olean_sha256": sha(OLean), "files": files,
            "maximum_artifact_path_length": max(len(str(x.resolve())) for x in paths),
            "Lean_started": False, "validated": False, "submission_ready": False}


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    group = p.add_mutually_exclusive_group(required=True)
    group.add_argument("--prepare", action="store_true")
    group.add_argument("--check", action="store_true")
    a = p.parse_args()
    print(json.dumps(prepare() if a.prepare else check(), indent=2))
